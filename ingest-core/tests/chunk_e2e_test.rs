// ---------------------------------------------------------------------------
// Deterministic payload generator — byte at absolute offset
// ---------------------------------------------------------------------------

fn generated_byte(offset: u64) -> u8 {
    (offset % 251) as u8
}

fn generated_bytes(start: u64, end_inclusive: u64) -> Vec<u8> {
    (start..=end_inclusive).map(generated_byte).collect()
}

// ---------------------------------------------------------------------------
// RangeServer — serves a Generated or File payload with Range support
// ---------------------------------------------------------------------------

enum Payload {
    /// Procedurally generated bytes — never touches disk.
    Generated { size: u64 },
    /// Bytes read from a real file via seek.
    File(PathBuf),
}

impl Payload {
    fn total_size(&self) -> u64 {
        match self {
            Payload::Generated { size } => *size,
            Payload::File(path) => std::fs::metadata(path)
                .expect("payload file metadata")
                .len(),
        }
    }
}

struct RangeServer {
    addr: std::net::SocketAddr,
    _handle: std::thread::JoinHandle<()>,
    shutdown: Arc<AtomicBool>,
}

impl RangeServer {
    fn start(payload: Payload) -> Self {
        let listener = StdTcpListener::bind("127.0.0.1:0").expect("bind range server");
        let addr = listener.local_addr().unwrap();
        let shutdown = Arc::new(AtomicBool::new(false));
        let shutdown_clone = shutdown.clone();

        let handle = std::thread::spawn(move || {
            listener.set_nonblocking(true).unwrap();
            loop {
                if shutdown_clone.load(Ordering::Relaxed) {
                    break;
                }
                match listener.accept() {
                    Ok((stream, _)) => {
                        let payload = match &payload {
                            Payload::Generated { size } => Payload::Generated { size: *size },
                            Payload::File(path) => Payload::File(path.clone()),
                        };
                        std::thread::spawn(move || {
                            Self::handle_connection(stream, payload);
                        });
                    }
                    Err(ref e) if e.kind() == std::io::ErrorKind::WouldBlock => {
                        std::thread::sleep(Duration::from_millis(10));
                        continue;
                    }
                    Err(e) => {
                        eprintln!("accept error: {e}");
                        break;
                    }
                }
            }
        });

        RangeServer {
            addr,
            _handle: handle,
            shutdown,
        }
    }

    fn url(&self) -> String {
        format!("http://127.0.0.1:{}/testfile.bin", self.addr.port())
    }

    fn handle_connection(mut stream: std::net::TcpStream, payload: Payload) {
        let total = payload.total_size();
        assert!(total > 0, "payload must be non-empty");

        let mut reader = BufReader::new(stream.try_clone().unwrap());
        let mut request_line = String::new();
        reader.read_line(&mut request_line).unwrap_or(0);

        // Consume headers, capturing Range.
        let mut range_header: Option<String> = None;
        loop {
            let mut line = String::new();
            reader.read_line(&mut line).unwrap_or(0);
            if line.trim().is_empty() {
                break;
            }
            let lower = line.to_lowercase();
            if let Some(val) = lower.strip_prefix("range:") {
                range_header = Some(val.trim().to_string());
            }
        }

        // Uploads (e.g. provider POSTs in other tests): drain and 200.
        if request_line.starts_with("POST") {
            let _ = std::io::copy(&mut reader, &mut std::io::empty());
            let response = "HTTP/1.1 200 OK\r\nContent-Length: 0\r\n\r\n";
            stream.write_all(response.as_bytes()).ok();
            return;
        }

        let is_head = request_line.starts_with("HEAD");

        let (start, end_inclusive) = if let Some(range) = range_header {
            let range_spec = range.trim().strip_prefix("bytes=").unwrap_or(range.trim());
            let parts: Vec<&str> = range_spec.split('-').collect();
            let start: u64 = parts.first().and_then(|s| s.parse().ok()).unwrap_or(0);
            let end: u64 = parts
                .get(1)
                .and_then(|s| s.parse().ok())
                .unwrap_or(total - 1);
            (start, end)
        } else {
            (0, total - 1)
        };

        // Clamp to the payload — faked sizes must not underflow.
        let start = start.min(total - 1);
        let end_inclusive = end_inclusive.min(total - 1);
        let len = end_inclusive - start + 1;

        let header = format!(
            "HTTP/1.1 200 OK\r\n\
             Content-Type: application/octet-stream\r\n\
             Content-Length: {len}\r\n\
             Accept-Ranges: bytes\r\n\
             \r\n",
        );
        stream.write_all(header.as_bytes()).ok();

        if is_head {
            return;
        }

        match payload {
            Payload::Generated { .. } => {
                let mut written: u64 = 0;
                let mut buf = [0u8; 8192];
                while written < len {
                    let n = std::cmp::min((len - written) as usize, buf.len());
                    for (i, b) in buf[..n].iter_mut().enumerate() {
                        *b = generated_byte(start + written + i as u64);
                    }
                    if stream.write_all(&buf[..n]).is_err() {
                        return;
                    }
                    written += n as u64;
                }
            }
            Payload::File(path) => {
                let mut f = std::fs::File::open(&path).expect("open payload file");
                f.seek(SeekFrom::Start(start)).expect("seek payload file");
                let mut remaining = len;
                let mut buf = [0u8; 8192];
                while remaining > 0 {
                    let n = std::cmp::min(remaining as usize, buf.len());
                    match f.read(&mut buf[..n]) {
                        Ok(0) => return,
                        Ok(read) => {
                            if stream.write_all(&buf[..read]).is_err() {
                                return;
                            }
                            remaining -= read as u64;
                        }
                        Err(_) => return,
                    }
                }
            }
        }
    }
}

impl Drop for RangeServer {
    fn drop(&mut self) {
        self.shutdown.store(true, Ordering::Relaxed);
    }
}

