/// A Range server claims a 256 MiB payload (generated on the fly) and the
/// pipeline chunks it into 16 × 16 MiB chunks. Verifies chunk spawn,
/// manifest contiguity, Merkle-root finalize, and full `DownloadFile`
/// reassembly (plus a chunk-boundary range read).
#[tokio::test]
async fn fake_256mib_file_chunks_and_reassembles() {
    let infra = common::infra().await;

    let server = RangeServer::start(Payload::Generated {
        size: FAKE_TOTAL_SIZE,
    });
    let url = server.url();

    let (tmp, yaml_path) = write_yaml(&url);
    let toml: TomlRawConfig = toml::from_str(TOML_FAKE_HUGE).expect("parse toml");

    let (file_job_id, services, shutdown, worker_handle) =
        enqueue_and_spawn_worker(&yaml_path, toml.clone(), &infra).await;

    let (mut client, grpc_shutdown) = start_grpc_server(services, toml).await;

    let mongo = MongoService::new(&infra.mongo_uri, 1, 16)
        .await
        .expect("mongo connect");

    // Wait for finalize. 16 chunks × 16 MiB download + gzip over loopback.
    let file_hash = wait_for_file_hash(&mongo, &file_job_id, Duration::from_secs(300)).await;
    let metadata = wait_for_metadata(&mongo, &file_hash, Duration::from_secs(300)).await;

    // --- Manifest checks ---
    let manifest = metadata.chunk_manifest.as_ref().expect("chunk_manifest");
    let expected_chunks = (FAKE_TOTAL_SIZE / FAKE_CHUNK_SIZE) as usize;
    assert_eq!(
        manifest.chunks.len(),
        expected_chunks,
        "expected {expected_chunks} chunks"
    );

    let mut sorted_chunks = manifest.chunks.clone();
    sorted_chunks.sort_by_key(|c| c.offset_start);
    for (i, chunk) in sorted_chunks.iter().enumerate() {
        assert_eq!(
            chunk.offset_start,
            i as u64 * FAKE_CHUNK_SIZE,
            "chunk {i}: offset_start mismatch"
        );
        let expected_end = std::cmp::min((i as u64 + 1) * FAKE_CHUNK_SIZE - 1, FAKE_TOTAL_SIZE - 1);
        assert_eq!(
            chunk.offset_end, expected_end,
            "chunk {i}: offset_end mismatch"
        );
        assert_eq!(
            chunk.compression, "gzip",
            "chunk {i}: expected gzip compression"
        );
        assert!(
            chunk.storage_path.ends_with(".gz"),
            "chunk {i}: storage_path should end with .gz: {}",
            chunk.storage_path
        );
    }
    assert_eq!(
        sorted_chunks.last().unwrap().offset_end,
        FAKE_TOTAL_SIZE - 1,
        "last chunk must end at FAKE_TOTAL_SIZE - 1"
    );

    assert_eq!(
        metadata.original_file_size, FAKE_TOTAL_SIZE,
        "original_file_size mismatch"
    );
    assert_eq!(
        manifest.compression.as_deref(),
        Some("gzip"),
        "manifest.compression should be Some(gzip)"
    );

    // Merkle root: 64 hex chars (NOT a content hash — see AGENTS.md).
    assert_eq!(
        metadata.file_hash.len(),
        64,
        "file_hash should be sha256 hex"
    );

    let file_job = mongo
        .get_file_job(&file_job_id)
        .await
        .expect("get file job")
        .expect("file job should exist");
    assert_eq!(file_job.status.as_str(), "completed");

    // --- Reassembly: full stream must match the generator ---
    let streamed =
        verify_full_stream(&mut client, &file_hash, FAKE_TOTAL_SIZE, generated_byte).await;
    assert_eq!(streamed, FAKE_TOTAL_SIZE);

    // --- Chunk-boundary range read (spans chunks 0 and 1) ---
    let range_start = FAKE_CHUNK_SIZE - 50;
    let range_end = FAKE_CHUNK_SIZE + 49;
    let expected = generated_bytes(range_start, range_end);
    verify_range(&mut client, &file_hash, range_start, range_end, &expected).await;

    // --- Cleanup ---
    let _ = grpc_shutdown.send(());
    shutdown_worker(&shutdown, worker_handle).await;
    let _ = mongo.delete_test_metadata(&file_hash).await;
    std::fs::remove_dir_all(&tmp).ok();
}

