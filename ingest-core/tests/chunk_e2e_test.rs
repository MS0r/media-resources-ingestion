//! End-to-end tests of the **chunking** and **reassembly** systems.
//!
//! Both tests run the full production pipeline:
//! enqueue → worker (HEAD → chunk spawn → per-chunk download + gzip →
//! finalize with Merkle root) → `DownloadFile` RPC reassembly.
//!
//! 1. `fake_256mib_file_chunks_and_reassembles` — a Range server *claims*
//!    a 256 MiB payload and generates bytes procedurally (never on disk).
//!    Exercises the "too much size" chunk-spawn path plus full
//!    reassembly of a large stream.
//! 2. `small_temp_file_chunks_and_reassembles` — a real 5 MiB temp file
//!    with `threshold_mb = 0`, proving that even a small file chunks
//!    when the threshold allows, and that reassembled bytes match the
//!    file exactly.
//!
//! MongoDB + Redis come from `common::infra()` (testcontainers, or the
//! `MONGODB_URI`/`REDIS_URI` env override).

