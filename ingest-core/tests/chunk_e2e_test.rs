fn sha256_hex(data: &[u8]) -> String {
    let mut h = Sha256::new();
    h.update(data);
    hex::encode(h.finalize())
}

async fn wait_for_file_hash(mongo: &MongoService, file_job_id: &str, timeout: Duration) -> String {
    let deadline = std::time::Instant::now() + timeout;
    loop {
        if let Ok(Some(job)) = mongo.get_file_job(file_job_id).await {
            if let Some(ref hash) = job.file_hash {
                return hash.clone();
            }
        }
        assert!(
            std::time::Instant::now() < deadline,
            "timed out waiting for file_hash on job {file_job_id}"
        );
        tokio::time::sleep(Duration::from_millis(200)).await;
    }
}

async fn wait_for_metadata(
    mongo: &MongoService,
    file_hash: &str,
    timeout: Duration,
) -> ingest_core::models::Metadata {
    let deadline = std::time::Instant::now() + timeout;
    loop {
        if let Ok(Some(meta)) = mongo.get_file_metadata(file_hash).await {
            if meta.chunk_manifest.is_some() {
                return meta;
            }
        }
        assert!(
            std::time::Instant::now() < deadline,
            "timed out waiting for chunk_manifest for hash {file_hash}"
        );
        tokio::time::sleep(Duration::from_millis(500)).await;
    }
}

/// Write a YAML config pointing at `url`, into a fresh tmp dir.
/// Returns (tmp_dir, yaml_path).
fn write_yaml(url: &str) -> (PathBuf, PathBuf) {
    let tmp = std::env::temp_dir().join(uuid::Uuid::new_v4().to_string());
    std::fs::create_dir_all(&tmp).unwrap();
    let dest_path = tmp.join("output");
    std::fs::create_dir_all(&dest_path).unwrap();
    let yaml_path = tmp.join("chunk-e2e.yaml");
    let yaml_content = format!(
        "path: {}\n\
         resources:\n\
           - url: {}\n\
             name: chunk_e2e_file\n",
        dest_path.display(),
        url
    );
    std::fs::write(&yaml_path, &yaml_content).unwrap();
    (tmp, yaml_path)
}

/// Boot a tonic `IngestServer` on an ephemeral port, sharing `services`
/// with the already-spawned worker. Returns (client, shutdown_tx).
async fn start_grpc_server(
    services: Arc<Services>,
    toml_config: TomlRawConfig,
) -> (IngestServiceClient<Channel>, oneshot::Sender<()>) {
    let ingest_server = grpc::IngestServer::new(services, toml_config);

    let listener = TcpListener::bind("127.0.0.1:0").await.expect("bind grpc");
    let addr = listener.local_addr().unwrap();
    let incoming = tokio_stream::wrappers::TcpListenerStream::new(listener);
    let (tx, rx) = oneshot::channel::<()>();

    tokio::spawn(async move {
        Server::builder()
            .add_service(IngestServiceServer::new(ingest_server))
            .serve_with_incoming_shutdown(incoming, async move {
                let _ = rx.await;
            })
            .await
            .expect("grpc server failed");
    });

    let endpoint = Endpoint::from_shared(format!("http://{addr}"))
        .expect("endpoint")
        .connect_lazy();
    let client = IngestServiceClient::new(endpoint);

    // Give the server a tick to start accepting.
    tokio::time::sleep(Duration::from_millis(100)).await;

    (client, tx)
}

/// Enqueue `yaml_path`, spawn the worker, and return
/// (file_job_id, services, shutdown, worker_handle).
async fn enqueue_and_spawn_worker(
    yaml_path: &PathBuf,
    toml: TomlRawConfig,
    infra: &common::Infra,
) -> (
    String,
    Arc<Services>,
    Arc<Shutdown>,
    tokio::task::JoinHandle<Result<(), ingest_core::ToolError>>,
) {
    let yaml_config = load_config(yaml_path).expect("load yaml");
    let args = RunConfig {
        yaml_path: yaml_path.to_path_buf(),
        dry_run: false,
        priority: Some(10),
        workers: None,
        follow: false,
        no_follow: true,
        output: OutputFormat::Json,
    };
    let config = AppConfig::from_sources(
        &yaml_config,
        toml,
        args,
        infra.redis_uri.clone(),
        infra.mongo_uri.clone(),
    );

    let batch_id = enqueue(&config, &yaml_config.resources)
        .await
        .expect("enqueue");
    assert!(!batch_id.is_empty(), "batch_id should not be empty");

    let mongo = MongoService::new(&infra.mongo_uri, 1, 16)
        .await
        .expect("mongo connect");
    let batch = mongo
        .get_batch(&batch_id)
        .await
        .expect("get batch")
        .expect("batch not found");
    assert_eq!(batch.job_ids.len(), 1, "expected exactly 1 file job");
    let file_job_id = batch.job_ids[0].clone();

    let services = Services::build(config).await.expect("services build");
    let shutdown = Shutdown::install(services.redis.clone());
    let worker = Worker::new(services.clone(), shutdown.clone(), 42);
    let worker_handle = worker.spawn();

    (file_job_id, services, shutdown, worker_handle)
}

async fn shutdown_worker(
    shutdown: &Arc<Shutdown>,
    worker_handle: tokio::task::JoinHandle<Result<(), ingest_core::ToolError>>,
) {
    shutdown.flag().store(true, Ordering::Relaxed);
    let _ = tokio::time::timeout(Duration::from_secs(10), worker_handle).await;
}

/// Verify a DownloadFile stream against an expected byte source and
/// return the total streamed length. `expected` maps absolute offset →
/// byte. Also verifies the header frame.
async fn verify_full_stream(
    client: &mut IngestServiceClient<Channel>,
    file_hash: &str,
    total_size: u64,
    expected: impl Fn(u64) -> u8,
) -> u64 {
    let response = client
        .download_file(proto::DownloadFileRequest {
            hash: file_hash.to_string(),
            range_start: None,
            range_end: None,
        })
        .await
        .expect("DownloadFile rpc")
        .into_inner();

    let mut stream = response;
    let mut collected: u64 = 0;
    let mut got_header = false;
    let mut block = vec![0u8; 8192];

    while let Some(msg) = stream.next().await {
        let frame = msg.expect("stream frame");
        match frame.payload {
            Some(proto::download_file_chunk::Payload::Header(h)) => {
                assert_eq!(h.file_hash, file_hash, "header file_hash");
                assert_eq!(h.total_size, total_size, "header total_size");
                assert!(h.is_chunked, "header should report is_chunked");
                got_header = true;
            }
            Some(proto::download_file_chunk::Payload::Data(b)) => {
                let mut off = 0usize;
                while off < b.len() {
                    let n = std::cmp::min(block.len(), b.len() - off);
                    for (i, byte) in block[..n].iter_mut().enumerate() {
                        *byte = expected(collected + off as u64 + i as u64);
                    }
                    assert_eq!(
                        &b[off..off + n],
                        &block[..n],
                        "payload mismatch at absolute offset {}",
                        collected + off as u64
                    );
                    off += n;
                }
                collected += b.len() as u64;
            }
            None => {}
        }
    }
    assert!(got_header, "missing header frame");
    assert_eq!(collected, total_size, "streamed length mismatch");
    collected
}

/// Verify a ranged DownloadFile read returns exactly the expected bytes.
async fn verify_range(
    client: &mut IngestServiceClient<Channel>,
    file_hash: &str,
    range_start: u64,
    range_end: u64,
    expected: &[u8],
) {
    let response = client
        .download_file(proto::DownloadFileRequest {
            hash: file_hash.to_string(),
            range_start: Some(range_start),
            range_end: Some(range_end),
        })
        .await
        .expect("DownloadFile range rpc")
        .into_inner();

    let mut stream = response;
    let mut collected = Vec::new();
    while let Some(msg) = stream.next().await {
        let frame = msg.expect("stream frame");
        if let Some(proto::download_file_chunk::Payload::Data(b)) = frame.payload {
            collected.extend_from_slice(&b);
        }
    }
    assert_eq!(
        collected.len(),
        expected.len(),
        "range [{range_start}, {range_end}]: length mismatch"
    );
    assert_eq!(
        collected, expected,
        "range [{range_start}, {range_end}]: content mismatch"
    );
}

